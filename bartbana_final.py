import evaluate
sacrebleu = evaluate.load("sacrebleu")

def postprocess_text(preds, labels):
    """
    - Loại bỏ token đặc biệt, strip(), ...
    - pred: list[str], label: list[str].
    """
    preds = [pred.strip() for pred in preds]
    labels = [lbl.strip() for lbl in labels]
    return preds, labels

def compute_metrics(eval_preds):
    """
    eval_preds = (predictions, labels)
    """
    preds, labels = eval_preds

    # Xử lý -100 --> pad_token_id
    preds = np.where(preds != -100, preds, tokenizer.pad_token_id)
    labels = np.where(labels != -100, labels, tokenizer.pad_token_id)

    # Giải mã
    pred_str = tokenizer.batch_decode(preds, skip_special_tokens=True)
    label_str = tokenizer.batch_decode(labels, skip_special_tokens=True)

    # Tiền xử lý để sacrebleu chính xác
    pred_str, label_str = postprocess_text(pred_str, label_str)

    # SacreBLEU yêu cầu references dưới dạng list of list
    # Mỗi sample: list[ reference1, reference2, ... ]
    # Ở đây chỉ 1 reference => [[ref1], [ref2], ...]
    references = [[l] for l in label_str]

    results = sacrebleu.compute(predictions=pred_str, references=references)
    return {"sacrebleu": results["score"]}  # "score" là BLEU của sacrebleu

