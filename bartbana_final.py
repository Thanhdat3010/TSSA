from transformers import AutoTokenizer, AutoModelForSeq2SeqLM
import evaluate
from torch.utils.data import DataLoader
import torch
from tqdm import tqdm  # Import tqdm for progress bar

# Load model and tokenizer
model_name = "BartBanaFinal-delete-original"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

# BLEU metric using `evaluate`
bleu = evaluate.load("sacrebleu")
meteor = evaluate.load("meteor")

# Ensure model is on the correct device
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model.to(device)

# Function to collate batches for the DataLoader
def collate_fn(batch):
    input_ids = torch.tensor([item["input_ids"] for item in batch], dtype=torch.long)
    attention_mask = torch.tensor([item["attention_mask"] for item in batch], dtype=torch.long)
    labels = torch.tensor([item["labels"] for item in batch], dtype=torch.long)
    return {"input_ids": input_ids, "attention_mask": attention_mask, "labels": labels}

# Wrap test_dataset with a DataLoader
batch_size = 64
test_dataloader = DataLoader(test_dataset, batch_size=batch_size, collate_fn=collate_fn)

# Evaluation function with progress bar
def evaluate_bleu(model, tokenizer, dataloader):
    model.eval()
    predictions = []
    references = []

    # Add progress bar
    with tqdm(total=len(dataloader), desc="Evaluating", unit="batch") as pbar:
        for batch in dataloader:
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels = batch["labels"].to(device)

            with torch.no_grad():
                outputs = model.generate(input_ids=input_ids, attention_mask=attention_mask, max_length=MAX_TARGET_LENGTH)

            # Decode predictions and references
            decoded_preds = tokenizer.batch_decode(outputs, skip_special_tokens=True)
            decoded_refs = tokenizer.batch_decode(labels, skip_special_tokens=True)

            predictions.extend(decoded_preds)
            references.extend([[ref] for ref in decoded_refs])  # BLEU expects a list of lists for references

            # Update progress bar
            pbar.update(1)

    # Compute BLEU score
    bleu_score = bleu.compute(predictions=predictions, references=references)
     # 🔸 Compute METEOR
    meteor_score = meteor.compute(predictions=predictions, references=references)
    return bleu_score["score"], meteor_score["meteor"]

# Evaluate on test dataset
# Gọi hàm và nhận 2 giá trị riêng biệt
bleu_score, meteor_score = evaluate_bleu(model, tokenizer, test_dataloader)

# In ra kết quả
print(f"BLEU Score: {bleu_score:.2f}")
print(f"METEOR Score: {meteor_score:.4f}")