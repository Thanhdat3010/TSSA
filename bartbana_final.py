def clean_text(text):
    """
    Làm sạch câu bằng cách:
    - Loại bỏ ký tự đặc biệt, xuống dòng, tab.
    - Xóa khoảng trắng thừa.
    """
    if not isinstance(text, str):
        return None
    text = re.sub(r'\\n|\|\\|[\n\r\t]', ' ', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

