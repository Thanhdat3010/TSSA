"""## 4. Offline alignment posterior `A` (Eq. 2)
Computed **once**, before training, and cached — never backpropagated through (Section 3.2: "an offline aligner
produces posterior matrix A"). We use LaBSE word-embedding cosine similarity as a lightweight, dependency-free
stand-in for SimAlign (the proposal explicitly allows "a strong multilingual encoder aligner", B4 family).
Words are then mapped onto BARTpho source subword spans (first-subword rule) so `A` is directly usable as
`A_ij` over source *tokens* `x_i`.
"""

labse = SentenceTransformer("sentence-transformers/LaBSE", device=DEVICE)
labse_word_model = labse[0].auto_model
labse_tok = labse.tokenizer

@torch.no_grad()
def labse_word_embeddings(words):
    '''Mean-pool LaBSE subword embeddings back to whitespace-word embeddings.'''
    enc = labse_tok(words, is_split_into_words=False, return_tensors="pt",
                     padding=True, truncation=True, max_length=32).to(DEVICE)
    out = labse_word_model(**enc).last_hidden_state  # (W, L, H) -- one row per word here since we embed word-by-word
    mask = enc["attention_mask"].unsqueeze(-1)
    pooled = (out * mask).sum(1) / mask.sum(1).clamp(min=1)
    return F.normalize(pooled, dim=-1)  # (W, H)

@torch.no_grad()
def offline_align_batch(src_texts, tgt_texts, src_token_offsets_batch):
    '''
    For each (src, tgt) sentence pair, compute a source-subtoken x target-subtoken posterior A (Eq.2):
      1. split into whitespace words, embed each word with LaBSE, cosine-similarity matrix
      2. softmax over target words per source word -> word-level posterior
      3. broadcast a word's posterior row to every BARTpho source subword belonging to that word (first-subword rule)
      4. broadcast target words -> target subwords the same way, using the tokenizer's target tokenization
    Returns a list of (m x n) numpy posterior matrices aligned to BARTpho src/tgt subword lengths.
    '''
    results = []
    for src_text, tgt_text in zip(src_texts, tgt_texts):
        src_words = src_text.split()
        tgt_words = tgt_text.split()
        if len(src_words) == 0 or len(tgt_words) == 0:
            results.append(np.zeros((1, 1), dtype=np.float32))
            continue
        se = labse_word_embeddings(src_words).cpu().numpy()
        te = labse_word_embeddings(tgt_words).cpu().numpy()
        sim = se @ te.T
        sim = sim / 0.05
        word_A = np.exp(sim - sim.max(axis=1, keepdims=True))
        word_A = word_A / word_A.sum(axis=1, keepdims=True)
        results.append(word_A)
    return results

def word_to_subword_map(text, tokenizer, max_len):
    '''Map each subword token index -> source word index (first-subword rule), truncated to max_len.'''
    words = text.split()
    ids = []
    word_of_token = []
    for wi, w in enumerate(words):
        sub = tokenizer(w, add_special_tokens=False)["input_ids"]
        if len(sub) == 0:
            continue
        ids.extend(sub)
        word_of_token.extend([wi] * len(sub))
    ids = ids[:max_len]
    word_of_token = word_of_token[:max_len]
    return ids, word_of_token, len(words)

def build_subword_posterior(src_text, tgt_text, word_A, tokenizer, max_src, max_tgt):
    _, src_w_of_t, n_src_w = word_to_subword_map(src_text, tokenizer, max_src)
    _, tgt_w_of_t, n_tgt_w = word_to_subword_map(tgt_text, tokenizer, max_tgt)
    m, n = len(src_w_of_t), len(tgt_w_of_t)
    if m == 0 or n == 0:
        return np.zeros((max(m,1), max(n,1)), dtype=np.float32)
    A = np.zeros((m, n), dtype=np.float32)
    wA = word_A[:min(word_A.shape[0], n_src_w), :min(word_A.shape[1], n_tgt_w)]
    for i, sw in enumerate(src_w_of_t):
        if sw >= wA.shape[0]:
            continue
        for j, tw in enumerate(tgt_w_of_t):
            if tw >= wA.shape[1]:
                continue
            A[i, j] = wA[sw, tw]
    return A

print('Offline aligner ready (LaBSE word-embedding cosine, mapped to BARTpho subwords).')

