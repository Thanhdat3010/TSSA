"""## 7. The three auxiliary losses (Eq. 2–4, 6–7)"""

def compute_lstruct(enc_hidden, src_mask, teacher_hidden, tgt_mask, A):
    '''
    Eq. 2-3.
      enc_hidden:    (B, m, H) source encoder states h^S_i
      teacher_hidden:(B, n, H) frozen teacher states h^T_j  (already computed on y, stop-gradiented)
      A:             (B, m, n) offline alignment posterior (rows normalized per Eq.2, unaligned rows -> all zero)
    '''
    eps = 1e-6
    A = A.to(enc_hidden.dtype)
    row_sum = A.sum(-1, keepdim=True)                       # (B,m,1)
    A_norm = A / (row_sum + eps)                             # A~_ij  (Eq. 2)
    h_bar_T = torch.bmm(A_norm, teacher_hidden)               # (B,m,H)  target barycenter per source position

    c_i = row_sum.squeeze(-1).clamp(max=1.0)                  # confidence c_i = min(1, sum_j A_ij)
    c_i = c_i * src_mask.float()                               # zero-out padding positions

    p_s = F.normalize(P_S(enc_hidden), dim=-1)
    p_t = F.normalize(P_T(h_bar_T), dim=-1).detach()          # stop-gradient sg(.) on teacher side (Eq. 3)

    per_pos = ((p_s - p_t) ** 2).sum(-1)                       # squared L2 of unit vectors, per source position
    loss = (c_i * per_pos).sum() / (c_i.sum() + eps)
    return loss


def compute_lprime(z_s, z_t):
    '''Eq. 4: in-batch InfoNCE, teacher side stop-gradiented, other targets in batch = negatives.'''
    z_s = F.normalize(z_s, dim=-1)
    z_t = F.normalize(z_t, dim=-1).detach()
    logits = z_s @ z_t.t() / TAU                               # (B,B)
    labels = torch.arange(z_s.size(0), device=z_s.device)
    return F.cross_entropy(logits, labels)


def compute_lroute(gated_modules, teacher_hidden, tgt_mask):
    '''
    Eq. 6-7. For every routed layer/head/step t:
      r_lht = (1 + cos(R_lh(o_lht), sg(P_T(h^T_t)))) / 2         (Eq.6, detached target)
      L_route = BCE(g_lht, r_lht)                                (Eq.7)
    '''
    p_t = F.normalize(P_T(teacher_hidden), dim=-1).detach()    # (B, n, proj_dim)
    mask = tgt_mask.float()
    total, count = 0.0, 0
    for g in gated_modules:
        if g.last_gates is None or g.last_head_outputs is None:
            continue
        gates = g.last_gates                                    # (B,heads,T)
        head_out = g.last_head_outputs                           # (B,heads,T,head_dim)
        T = gates.shape[-1]
        n = p_t.shape[1]
        Tm = min(T, n)
        for h in range(g.num_heads):
            proj = F.normalize(g.R[h](head_out[:, h, :Tm]), dim=-1)    # (B,Tm,proj_dim)
            r = (1 + (proj * p_t[:, :Tm]).sum(-1)) / 2                  # (B,Tm) in [0,1], detached via p_t.detach()
            r = r.detach().clamp(1e-4, 1 - 1e-4)
            g_h = gates[:, h, :Tm].clamp(1e-4, 1 - 1e-4)
            bce = -(r * torch.log(g_h) + (1 - r) * torch.log(1 - g_h))
            m = mask[:, :Tm]
            total = total + (bce * m).sum()
            count = count + m.sum()
    if count == 0:
        return torch.tensor(0.0, device=teacher_hidden.device)
    return total / count

"""## 8. Unified TSSA training step
Implements the lambda ramp, the routing-activation switch, and the **hard budget check**
(`sum(aux) <= L_MT`) with automatic shrink, exactly as you specified.
"""

TOTAL_STEPS = (len(train_loader) // GRAD_ACCUM) * EPOCHS
WARMUP_STEPS = int(TOTAL_STEPS * WARMUP_RATIO)
RAMP_STEPS = max(1, TOTAL_STEPS // 3)
ROUTE_START_STEP = RAMP_STEPS

lambda1_cur, lambda2_cur, lambda3_cur = LAMBDA1, LAMBDA2, LAMBDA3
budget_violations, budget_window = 0, 0

optim_params = list(student.parameters()) + list(P_S.parameters()) + list(P_T.parameters())
optimizer = torch.optim.AdamW(optim_params, lr=LR, weight_decay=0.01)
scheduler = get_linear_schedule_with_warmup(optimizer, WARMUP_STEPS, TOTAL_STEPS)
scaler = torch.amp.GradScaler("cuda")

def lambda_at(step):
    ramp = min(1.0, step / RAMP_STEPS)
    l1 = lambda1_cur * ramp
    l2 = lambda2_cur * ramp
    l3 = lambda3_cur if step >= ROUTE_START_STEP else 0.0
    return l1, l2, l3

def training_step(batch, step):
    global lambda1_cur, lambda2_cur, lambda3_cur, budget_violations, budget_window

    input_ids = batch["input_ids"].to(DEVICE)
    attn_mask = batch["attention_mask"].to(DEVICE)
    labels = batch["labels"].to(DEVICE)
    dec_in = batch["decoder_input_ids"].to(DEVICE)
    dec_mask = batch["decoder_attention_mask"].to(DEVICE)
    A = batch["A"].to(DEVICE)

    routing_now = step >= ROUTE_START_STEP
    set_routing(routing_now)

    with torch.no_grad():
        teacher_hidden = teacher_encoder(input_ids=dec_in, attention_mask=dec_mask).last_hidden_state

    with torch.amp.autocast("cuda"):
        enc_out = student.model.encoder(input_ids=input_ids, attention_mask=attn_mask)
        enc_hidden = enc_out.last_hidden_state
        src_summary = mask_mean_pool(enc_hidden, attn_mask)
        set_source_summary(src_summary)

        out = student(input_ids=None, attention_mask=attn_mask, encoder_outputs=enc_out, labels=labels)
        L_mt = out.loss

        L_struct = compute_lstruct(enc_hidden, attn_mask, teacher_hidden, dec_mask, A)

        z_s = mask_mean_pool(P_S(enc_hidden), attn_mask)
        z_t = mask_mean_pool(P_T(teacher_hidden), dec_mask)
        L_prime = compute_lprime(z_s, z_t)

        L_route = compute_lroute(gated_modules, teacher_hidden, dec_mask) if routing_now else torch.tensor(0.0, device=DEVICE)

        l1, l2, l3 = lambda_at(step)
        aux_total = l1 * L_struct + l2 * L_prime + l3 * L_route
        loss = L_mt + aux_total

    budget_window += 1
    if aux_total.item() > L_mt.item():
        budget_violations += 1
    if budget_window >= BUDGET_CHECK_EVERY:
        if budget_violations / budget_window > 0.3:
            lambda1_cur *= BUDGET_SHRINK_FACTOR
            lambda2_cur *= BUDGET_SHRINK_FACTOR
            lambda3_cur *= BUDGET_SHRINK_FACTOR
            print(f"[budget guard] step {step}: aux exceeded L_MT on "
                  f"{budget_violations}/{budget_window} checks -> shrinking lambdas to "
                  f"({lambda1_cur:.3f}, {lambda2_cur:.3f}, {lambda3_cur:.3f})")
        budget_violations, budget_window = 0, 0

    return loss, {"L_mt": L_mt.item(), "L_struct": L_struct.item(),
                  "L_prime": L_prime.item(), "L_route": float(L_route.item()) if torch.is_tensor(L_route) else L_route,
                  "lambda1": l1, "lambda2": l2, "lambda3": l3, "routing": routing_now}

"""## 9. Evaluation: BLEU + chrF++ (sacrebleu, corpus-level, detokenized)
Matches Section 4.6: sacreBLEU and chrF++ as primary metrics, generation via `model.generate`, greedy/beam decode,
same decoding script for every epoch.
"""

@torch.no_grad()
def evaluate(loader, max_new_tokens=MAX_TGT_LEN, num_beams=4, limit_batches=None):
    student.eval()
    set_routing(True)  # inference always uses learned routing (it only needs q & s, both available at inference)
    hyps, refs = [], []
    for bi, batch in enumerate(loader):
        if limit_batches is not None and bi >= limit_batches:
            break
        input_ids = batch["input_ids"].to(DEVICE)
        attn_mask = batch["attention_mask"].to(DEVICE)
        enc_out = student.model.encoder(input_ids=input_ids, attention_mask=attn_mask)
        src_summary = mask_mean_pool(enc_out.last_hidden_state, attn_mask)
        set_source_summary(src_summary)

        gen = student.generate(encoder_outputs=enc_out, attention_mask=attn_mask,
                                max_new_tokens=max_new_tokens, num_beams=num_beams,
                                decoder_start_token_id=student.config.decoder_start_token_id)
        decoded_hyp = tokenizer.batch_decode(gen, skip_special_tokens=True)

        labels = batch["labels"].clone()
        labels[labels == -100] = tokenizer.pad_token_id
        decoded_ref = tokenizer.batch_decode(labels, skip_special_tokens=True)

        hyps.extend(decoded_hyp)
        refs.extend(decoded_ref)
    student.train()

    bleu = sacrebleu.corpus_bleu(hyps, [refs])
    chrf = sacrebleu.corpus_chrf(hyps, [refs], word_order=2)  # chrF++ = chrF with word_order=2
    return {"BLEU": bleu.score, "chrF++": chrf.score, "n": len(hyps)}

