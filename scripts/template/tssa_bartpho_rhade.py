import pickle

def precompute_alignments(ds, cache_path, max_src=MAX_SRC_LEN, max_tgt=MAX_TGT_LEN, chunk=64):
    if os.path.exists(cache_path):
        with open(cache_path, "rb") as f:
            return pickle.load(f)
    cache = []
    srcs, tgts = ds["src"], ds["tgt"]
    for start in range(0, len(srcs), chunk):
        s_chunk = srcs[start:start+chunk]
        t_chunk = tgts[start:start+chunk]
        word_As = offline_align_batch(s_chunk, t_chunk, None)
        for s, t, wA in zip(s_chunk, t_chunk, word_As):
            A = build_subword_posterior(s, t, wA, tokenizer, max_src, max_tgt)
            cache.append(A.astype(np.float16))
        if start % (chunk*10) == 0:
            print(f"  aligned {start+len(s_chunk)}/{len(srcs)}")
    with open(cache_path, "wb") as f:
        pickle.dump(cache, f)
    return cache

