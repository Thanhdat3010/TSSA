"""## 6. TSSA modules: projections `P_S`/`P_T`, sentence pooling, and **gated cross-attention** (Eq. 5–7)
The gated attention module is a drop-in replacement for BARTpho's decoder cross-attention: it computes attention
exactly as before, but additionally produces a per-head scalar gate `g_lht = σ(MLP([q; s; q⊙s]))` (Eq. 5) applied
to that head's output **before** the output projection. This only uses inference-time quantities, so the gate is
active at inference too (no target leakage — Section 3.1).
"""

class Projector(nn.Module):
    def __init__(self, in_dim, out_dim=PROJ_DIM):
        super().__init__()
        self.net = nn.Linear(in_dim, out_dim)
    def forward(self, x):
        return F.normalize(self.net(x), dim=-1)

P_S = Projector(HID).to(DEVICE)
P_T = Projector(HID).to(DEVICE)

def mask_mean_pool(hidden, mask):
    mask = mask.unsqueeze(-1).float()
    return (hidden * mask).sum(1) / mask.sum(1).clamp(min=1e-6)


class GatedCrossAttention(nn.Module):
    '''Wraps an existing BartAttention (decoder.encoder_attn) with head-wise routing (Eq. 5-7).
    The source summary `s` is computed INSIDE forward from key_value_states, so it is always
    correctly shaped even under beam-search batch expansion.'''
    def __init__(self, orig_attn, layer_idx, proj_dim=PROJ_DIM):
        super().__init__()
        self.embed_dim = orig_attn.embed_dim
        self.num_heads = orig_attn.num_heads
        self.head_dim = self.embed_dim // self.num_heads
        self.scaling = self.head_dim ** -0.5
        self.layer_idx = layer_idx

        self.k_proj = orig_attn.k_proj
        self.v_proj = orig_attn.v_proj
        self.q_proj = orig_attn.q_proj
        self.out_proj = orig_attn.out_proj

        self.router = nn.ModuleList([
            nn.Sequential(nn.Linear(self.head_dim * 3, 32), nn.ReLU(), nn.Linear(32, 1))
            for _ in range(self.num_heads)
        ])
        self.s_proj = nn.Linear(self.embed_dim, self.embed_dim)
        self.R = nn.ModuleList([nn.Linear(self.head_dim, proj_dim) for _ in range(self.num_heads)])

        self.routing_enabled = False
        self.last_gates = None
        self.last_head_outputs = None

    def _shape(self, x, B, T):
        return x.view(B, T, self.num_heads, self.head_dim).transpose(1, 2)

    def _pooled_source_summary(self, key_value_states, attention_mask):
        '''Mean-pool key_value_states over the source length using the encoder padding mask,
        derived from the additive attention_mask (0 = keep, large negative = masked).'''
        B, S, _ = key_value_states.shape
        if attention_mask is not None:
            am = attention_mask
            while am.dim() > 2:
                am = am[:, 0]          # (B, 1, tgt_len, src_len) or (B, 1, src_len) -> (B, src_len)
            if am.shape[-1] != S:
                am = am[:, :S] if am.shape[-1] > S else F.pad(am, (0, S - am.shape[-1]))
            bin_mask = (am >= -1.0).float()   # additive mask ~0 for keep, very negative for masked
        else:
            bin_mask = torch.ones(B, S, device=key_value_states.device)
        denom = bin_mask.sum(1, keepdim=True).clamp(min=1e-6)
        return (key_value_states * bin_mask.unsqueeze(-1)).sum(1) / denom  # (B, embed_dim)

    def forward(self, hidden_states, key_value_states, attention_mask=None, **kwargs):
        B, T, _ = hidden_states.shape
        q = self._shape(self.q_proj(hidden_states) * self.scaling, B, T)
        k = self._shape(self.k_proj(key_value_states), B, key_value_states.shape[1])
        v = self._shape(self.v_proj(key_value_states), B, key_value_states.shape[1])

        attn_weights = torch.matmul(q, k.transpose(-1, -2))
        if attention_mask is not None:
            attn_weights = attn_weights + attention_mask
        attn_weights = F.softmax(attn_weights, dim=-1)
        head_out = torch.matmul(attn_weights, v)
        self.last_head_outputs = head_out

        src_summary = self._pooled_source_summary(key_value_states, attention_mask)  # (B, embed_dim)
        s = self.s_proj(src_summary)
        s = s.view(B, self.num_heads, self.head_dim).unsqueeze(2).expand(-1, -1, T, -1)

        if self.routing_enabled:
            gates = []
            for h in range(self.num_heads):
                gin = torch.cat([q[:, h] / self.scaling, s[:, h], (q[:, h] / self.scaling) * s[:, h]], dim=-1)
                g_h = torch.sigmoid(self.router[h](gin)).squeeze(-1)
                gates.append(g_h)
            gates = torch.stack(gates, dim=1)
            gated = head_out * gates.unsqueeze(-1)
        else:
            gates = torch.ones(B, self.num_heads, T, device=head_out.device)
            gated = head_out

        self.last_gates = gates
        out = gated.transpose(1, 2).contiguous().view(B, T, self.embed_dim)
        out = self.out_proj(out)
        return out, attn_weights

