def collate(batch, with_align):
    src_texts = [b["src"] for b in batch]
    tgt_texts = [b["tgt"] for b in batch]

    src_enc = tokenizer(src_texts, padding=True, truncation=True, max_length=MAX_SRC_LEN, return_tensors="pt")
    tgt_enc = tokenizer(text_target=tgt_texts, padding=True, truncation=True, max_length=MAX_TGT_LEN, return_tensors="pt")

    labels = tgt_enc["input_ids"].clone()
    labels[labels == tokenizer.pad_token_id] = -100

    out = {
        "input_ids": src_enc["input_ids"],
        "attention_mask": src_enc["attention_mask"],
        "labels": labels,
        "decoder_input_ids": tgt_enc["input_ids"],           # teacher input to E_T (same tokenizer as decoder)
        "decoder_attention_mask": tgt_enc["attention_mask"],
    }
    if with_align:
        m = src_enc["input_ids"].shape[1]
        n = tgt_enc["input_ids"].shape[1]
        A_batch = torch.zeros(len(batch), m, n, dtype=torch.float32)
        for bi, b in enumerate(batch):
            A = b["A"]
            mi, ni = min(A.shape[0], m), min(A.shape[1], n)
            A_batch[bi, :mi, :ni] = torch.from_numpy(A[:mi, :ni].astype(np.float32))
        out["A"] = A_batch
    return out

